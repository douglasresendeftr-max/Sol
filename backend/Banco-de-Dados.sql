CREATE DATABASE IF NOT EXISTS Sol
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;
USE Sol;
CREATE TABLE IF NOT EXISTS mensagens (
  id INT AUTO_INCREMENT NOT NULL PRIMARY KEY,
  nome VARCHAR(60) NOT NULL,
  email VARCHAR(120) NOT NULL,
  nomep VARCHAR(60) NOT NULL,
  assunto VARCHAR(20) NOT NULL,
  mensagem TEXT NOT NULL,
  criada_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE produtos (
  id_produto AUTO_INCREMENT NOT NULL PRIMARY KEY,
  precoP VARCHAR(10) NOT NULL,
  QuantidadeE VARCHAR(10) NOT NULL,
  NomeP VARCHAR(50) NOT NULL,
  Descricao VARCHAR(300) NOT NULL,
  Categoria VARCHAR(40) NOT NULL
);

CREATE TABLE agendamento (
  id_agendamento AUTO_INCREMENT NOT NULL PRIMARY KEY,
  dataA VARCHAR(10) NOT NULL,
  horario VARCHAR(7) NOT NULL,
  TipoA VARCHAR(40) NOT NULL,
);

